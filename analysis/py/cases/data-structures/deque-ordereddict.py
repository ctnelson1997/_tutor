# deque (rotate both ways, extendleft reverses, maxlen drops from the far end) and OrderedDict moves/equality
from collections import deque, OrderedDict

line = deque(["a", "b", "c", "d"])
line.rotate(-1)
print(line)
line.rotate(2)
print(line)
line.extendleft([1, 2])
print(line, line[0], line[-1])
window = deque([1, 2, 3], maxlen=3)
window.append(4)
print(window)
window.appendleft(0)
print(window, window.maxlen)
window.extend([7, 8])
print(window, 8 in window, window.index(7))
front = line.popleft()
back = line.pop()
print(front, back, list(line), len(line))
line.remove("a")
line.insert(1, "z")
print(line, line.count("z"))

cache = OrderedDict()
for key in ["x", "y", "z"]:
    cache[key] = ord(key)
cache.move_to_end("x")
cache.move_to_end("z", last=False)
print(cache)
oldest = cache.popitem(last=False)
newest = cache.popitem()
print(oldest, newest, cache)
o1 = OrderedDict(a=1, b=2)
o2 = OrderedDict(b=2, a=1)
print(o1 == o2, o1 == dict(o2), dict(o1) == dict(o2))
